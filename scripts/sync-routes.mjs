// Generates each app's page files from core/src/routes.json, so every platform
// has the same screens without hand-copying. Run: pnpm sync:routes
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const routes = JSON.parse(readFileSync(path.join(root, 'core/src/routes.json'), 'utf8'));
const MARKER = '// Generated by scripts/sync-routes.mjs — do not edit.';

const apps = readdirSync(path.join(root, 'apps')).filter((a) => existsSync(path.join(root, 'apps', a, 'app', 'layout.tsx')));

function pageSource(screen) {
  return `${MARKER}
'use client';

import { Suspense } from 'react';
import { ${screen} } from '@supplyline/core/screens';

export default function Page() {
  return (
    <Suspense>
      <${screen} />
    </Suspense>
  );
}
`;
}

function removeStale(dir, keep) {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) {
      removeStale(full, keep);
      if (readdirSync(full).length === 0) rmSync(full, { recursive: true });
    } else if (entry === 'page.tsx' && !keep.has(full) && readFileSync(full, 'utf8').startsWith(MARKER)) {
      rmSync(full);
      console.log(`  removed ${path.relative(root, full)}`);
    }
  }
}

for (const app of apps) {
  const appDir = path.join(root, 'apps', app, 'app');
  const keep = new Set();
  for (const r of routes) {
    const file = path.join(appDir, ...r.path.split('/').filter(Boolean), 'page.tsx');
    keep.add(file);
    mkdirSync(path.dirname(file), { recursive: true });
    const src = pageSource(r.screen);
    if (!existsSync(file) || readFileSync(file, 'utf8') !== src) writeFileSync(file, src);
  }
  removeStale(appDir, keep);
  console.log(`apps/${app}: ${routes.length} routes`);
}
